-- plasma-manager leaves keys unlocked; true marks every key [$i], which also freezes those settings in System Settings
local lock = false

local function rc(values)
  return { merge = { format = "kconfig", values = values }, mutable = not lock }
end

-- kglobalshortcutsrc's "keys,default,name" form; no keys means none
local function sc(...)
  local keys = { ... }
  return (#keys == 0 and "none" or table.concat(keys, "\\t")) .. ",,"
end

